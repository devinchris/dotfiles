#!/usr/bin/env python3
"""Regenerate verification/rtm.md and lint the spec.

Run from the documentation/ folder:  python3 verification/gen_rtm.py
Checks: duplicate requirement IDs, TBD/TBR referenced but not in open-questions.md
(and vice versa). Existing Test/Impl./Status cells in rtm.md are preserved.
"""
import glob
import os
import re
import sys

REQ = re.compile(r'\|\s*((?:REQ-[A-Z]+|SYS|NFR)-\d{3})\s*\|(.*)')
VERIF = re.compile(r'[TDIA](, ?[TDIA])*|—')


def collect():
    files = (sorted(glob.glob('07-*.md')) + sorted(glob.glob('stories/US-*.md'))
             + sorted(glob.glob('components/*.md')))
    rows = []
    for f in files:
        story = re.match(r'stories/(US-\d+)', f)
        src = story.group(1) if story else ('SYS/NFR' if f.startswith('07') else os.path.basename(f)[:-3])
        for line in open(f, encoding='utf-8'):
            m = REQ.match(line)
            if m:
                cells = [c.strip() for c in m.group(2).split('|')]
                verif = next((c for c in cells if VERIF.fullmatch(c)), '')
                rows.append((m.group(1), src, f, verif))
    return rows


def previous_state(path='verification/rtm.md'):
    state = {}
    if os.path.exists(path):
        for line in open(path, encoding='utf-8'):
            cells = [c.strip() for c in line.strip().strip('|').split('|')]
            if len(cells) == 7 and re.match(r'(REQ-[A-Z]+|SYS|NFR)-\d{3}', cells[0]):
                state[cells[0]] = cells[4:7]
    return state


def main():
    rows = collect()
    ids = [r[0] for r in rows]
    dups = sorted({i for i in ids if ids.count(i) > 1})
    prev = previous_state()
    out = ["# Requirements Traceability Matrix (RTM)", "",
           "Generated by `verification/gen_rtm.py` from the requirement tables. "
           "Do not hand-edit the ID/Source/Defined in/Verif. columns; re-run the script after spec edits.",
           "Agents update **Test / evidence**, **Impl.** (file or commit) and **Status**.", "",
           "| Requirement | Source | Defined in | Verif. | Test / evidence | Impl. | Status |",
           "|---|---|---|---|---|---|---|"]
    for i, s, f, v in rows:
        test, impl, status = prev.get(i, ['', '', 'Draft'])
        out.append(f"| {i} | {s} | [{os.path.basename(f)}](../{f}) | {v} | {test} | {impl} | {status} |")
    open('verification/rtm.md', 'w', encoding='utf-8').write('\n'.join(out) + '\n')

    docs = [p for p in glob.glob('**/*.md', recursive=True)
            if 'open-questions' not in p and not p.startswith('archive')]
    referenced = set(re.findall(r'TB[DR]-\d{3}', ''.join(open(p, encoding='utf-8').read() for p in docs)))
    registered = set(re.findall(r'^\| (TB[DR]-\d{3})', open('open-questions.md', encoding='utf-8').read(), re.M))
    missing, unused = sorted(referenced - registered), sorted(registered - referenced)

    print(f"{len(rows)} requirements written to verification/rtm.md")
    ok = True
    if dups:
        ok = False
        print("ERROR duplicate IDs:", ', '.join(dups))
    if missing:
        ok = False
        print("ERROR TBD/TBR not in open-questions.md:", ', '.join(missing))
    if unused:
        print("WARN registered but unreferenced:", ', '.join(unused))
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
